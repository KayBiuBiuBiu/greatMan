print("如何识别真正的底部?")
print("=" * 70)

print("""
底部的特征:

1. 价格跌到关键支撑位
   - 20日均线以下 10%+
   - 或历史支撑位

2. RSI 极度超卖
   - RSI < 20 (不是 < 35)
   - 表示真正的底部

3. 成交量特征
   - 高位: 成交量萎缩
   - 低位: 成交量止跌回升

4. 技术形态
   - 双底/三底形态
   - V型反转
   - 长下影线

5. 时间特征
   - 经过充分下跌 (10%+)
   - 停留在底部 2-3 天

正确的底部进场:
  价格 < 20日线 12% 左右
  + RSI < 20
  + 出现止跌信号 (如长下影线)
  = 底部确认
""")

print("\n" + "=" * 70)
print("新方案：分阶段布局而非一次性追风")
print("=" * 70)

print("""
阶段1 - 底部确认 (RSI<25, 价格低10%+):
  买入 1/3 头寸 (轻仓试探)
  
阶段2 - 支撑确认 (反弹后再次逼近底部):
  加仓到 2/3
  
阶段3 - 反弹启动 (金叉出现):
  加仓到满仓
  
优势:
  • 从底部就开始布局 (而不是反弹快结束才买)
  • 分散风险，摊低成本
  • 反弹确认时已经有了仓位
  • 避免买在最高处

效果对比:

场景: 从 14.00 跌到 12.00, 反弹到 15.00

旧方案(在12.80金叉时全买):
  买入价: 12.80
  卖出价: 15.00
  收益: +17.2%
  风险: 如果反转亏 -6.3%

新方案(分阶段布局):
  12.00: 买1/3 (成本12.00)
  12.90: 加仓到2/3 (平均成本12.40)
  12.80: 金叉加到满 (平均成本12.50)
  卖出: 15.00
  
  收益: +20.0% (更高!)
  风险: 反转时亏 -4.0% (更低!)
  
  关键: 平均成本低了3%, 收益高了3%
""")

